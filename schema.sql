-- Data Analysis for Business and Decision-Making
-- Database: PostgreSQL 14+
-- Domain: Retail sales + employee attrition analytics

BEGIN;

DROP VIEW IF EXISTS vw_monthly_sales CASCADE;
DROP VIEW IF EXISTS vw_customer_lifetime_value CASCADE;
DROP VIEW IF EXISTS vw_employee_attrition_summary CASCADE;
DROP TABLE IF EXISTS employee_status_history CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS customers CASCADE;

CREATE TABLE customers (
    customer_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        VARCHAR(80) NOT NULL,
    last_name         VARCHAR(80) NOT NULL,
    email             VARCHAR(255) NOT NULL UNIQUE,
    city              VARCHAR(100),
    state             VARCHAR(100),
    signup_date       DATE NOT NULL DEFAULT CURRENT_DATE,
    customer_segment  VARCHAR(30) NOT NULL DEFAULT 'Standard'
                      CHECK (customer_segment IN ('Standard', 'Silver', 'Gold', 'Platinum'))
);

CREATE TABLE products (
    product_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name     VARCHAR(150) NOT NULL,
    category         VARCHAR(80) NOT NULL,
    unit_price       NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE employees (
    employee_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name        VARCHAR(80) NOT NULL,
    last_name         VARCHAR(80) NOT NULL,
    department        VARCHAR(80) NOT NULL,
    job_title         VARCHAR(100) NOT NULL,
    hire_date         DATE NOT NULL,
    termination_date  DATE,
    annual_salary     NUMERIC(12,2) CHECK (annual_salary >= 0),
    employment_status VARCHAR(20) NOT NULL DEFAULT 'Active'
                      CHECK (employment_status IN ('Active', 'Terminated', 'Leave')),
    CHECK (termination_date IS NULL OR termination_date >= hire_date),
    CHECK (
      (employment_status = 'Terminated' AND termination_date IS NOT NULL)
      OR (employment_status <> 'Terminated' AND termination_date IS NULL)
    )
);

CREATE TABLE orders (
    order_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    BIGINT NOT NULL REFERENCES customers(customer_id),
    order_date     DATE NOT NULL DEFAULT CURRENT_DATE,
    order_status   VARCHAR(20) NOT NULL DEFAULT 'Completed'
                   CHECK (order_status IN ('Pending', 'Completed', 'Cancelled', 'Returned')),
    sales_channel  VARCHAR(20) NOT NULL DEFAULT 'Online'
                   CHECK (sales_channel IN ('Online', 'Store', 'Phone')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE order_items (
    order_item_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    product_id     BIGINT NOT NULL REFERENCES products(product_id),
    quantity       INTEGER NOT NULL CHECK (quantity > 0),
    unit_price     NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    discount_pct   NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    UNIQUE (order_id, product_id)
);

CREATE TABLE employee_status_history (
    history_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     BIGINT NOT NULL REFERENCES employees(employee_id) ON DELETE CASCADE,
    status          VARCHAR(20) NOT NULL CHECK (status IN ('Active', 'Terminated', 'Leave')),
    effective_date  DATE NOT NULL,
    notes           TEXT,
    UNIQUE (employee_id, effective_date)
);

CREATE INDEX idx_orders_order_date ON orders(order_date);
CREATE INDEX idx_orders_customer_id ON orders(customer_id);
CREATE INDEX idx_order_items_product_id ON order_items(product_id);
CREATE INDEX idx_employees_department_status ON employees(department, employment_status);
CREATE INDEX idx_employee_history_effective_date ON employee_status_history(effective_date);

-- Reporting view: monthly completed sales.
CREATE VIEW vw_monthly_sales AS
SELECT
    DATE_TRUNC('month', o.order_date)::DATE AS sales_month,
    COUNT(DISTINCT o.order_id) AS order_count,
    COUNT(DISTINCT o.customer_id) AS purchasing_customers,
    ROUND(SUM(oi.quantity * oi.unit_price * (1 - oi.discount_pct / 100.0)), 2) AS net_sales
FROM orders o
JOIN order_items oi ON oi.order_id = o.order_id
WHERE o.order_status = 'Completed'
GROUP BY DATE_TRUNC('month', o.order_date)::DATE;

-- Reporting view: customer lifetime value based on completed orders.
CREATE VIEW vw_customer_lifetime_value AS
SELECT
    c.customer_id,
    c.first_name,
    c.last_name,
    c.customer_segment,
    COUNT(DISTINCT o.order_id) FILTER (WHERE o.order_status = 'Completed') AS completed_orders,
    ROUND(COALESCE(SUM(oi.quantity * oi.unit_price * (1 - oi.discount_pct / 100.0))
        FILTER (WHERE o.order_status = 'Completed'), 0), 2) AS lifetime_value
FROM customers c
LEFT JOIN orders o ON o.customer_id = c.customer_id
LEFT JOIN order_items oi ON oi.order_id = o.order_id
GROUP BY c.customer_id, c.first_name, c.last_name, c.customer_segment;

-- Reporting view: current employee counts by department.
CREATE VIEW vw_employee_attrition_summary AS
SELECT
    department,
    COUNT(*) AS total_employees,
    COUNT(*) FILTER (WHERE employment_status = 'Active') AS active_employees,
    COUNT(*) FILTER (WHERE employment_status = 'Terminated') AS terminated_employees,
    ROUND(
      100.0 * COUNT(*) FILTER (WHERE employment_status = 'Terminated')
      / NULLIF(COUNT(*), 0), 2
    ) AS cumulative_termination_pct
FROM employees
GROUP BY department;

COMMIT;
